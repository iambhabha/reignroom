import { z } from "zod";
import {
  CHAT_MAX,
  NAME_MAX,
  PLAYER_COUNTS,
  PROTOCOL_VERSION,
  ROOM_CODE_ALPHABET,
  ROOM_CODE_LENGTH,
  SLOTS,
} from "./constants.ts";

// ── Primitives ──────────────────────────────────────────────────────────────

export const RoomCode = z
  .string()
  .regex(new RegExp(`^[${ROOM_CODE_ALPHABET}]{${ROOM_CODE_LENGTH}}$`));

/** Public per-connection id, 12 base64url chars. Shared with other members. */
export const PeerId = z.string().regex(/^[A-Za-z0-9_-]{12}$/);
/** Secret, 32 random bytes as base64url. Never shared with other members. */
export const Secret = z.string().regex(/^[A-Za-z0-9_-]{43}$/);

export const SlotSchema = z.literal(SLOTS);
export const PlayerCountSchema = z.literal(PLAYER_COUNTS);

/** Raw input limits; the server cleans text with cleanText() before use. */
const Name = z.string().min(1).max(NAME_MAX * 4);
const ChatText = z.string().min(1).max(CHAT_MAX * 4);

/** Generous upper bound; real offers with H.264 + VP8 are ~5–10 KB. */
const SDP_MAX = 40_000;

const IceCandidate = z.strictObject({
  candidate: z.string().max(1024),
  sdpMid: z.string().max(64).nullable().optional(),
  sdpMLineIndex: z.int().min(0).max(64).nullable().optional(),
  usernameFragment: z.string().max(256).nullable().optional(),
});

// ── Client → room ───────────────────────────────────────────────────────────

export const ClientMsg = z.discriminatedUnion("t", [
  /** Must be the first message on a socket. */
  z.strictObject({
    t: z.literal("hello"),
    v: z.literal(PROTOCOL_VERSION),
    name: Name,
    /** Present only for the room creator; grants host rights. */
    hostKey: Secret.optional(),
    /** From a previous `welcome`; reclaims the same seat after a reconnect. */
    resume: Secret.optional(),
  }),
  z.strictObject({ t: z.literal("slot"), slot: SlotSchema.nullable() }),
  z.strictObject({ t: z.literal("ready"), ready: z.boolean() }),
  z.strictObject({ t: z.literal("chat"), text: ChatText }),
  z.strictObject({ t: z.literal("leave") }),
  // Host only
  z.strictObject({ t: z.literal("kick"), peer: PeerId }),
  z.strictObject({ t: z.literal("config"), players: PlayerCountSchema }),
  z.strictObject({ t: z.literal("stream"), live: z.boolean() }),
  /** Locked rooms refuse new members; existing members can still reconnect. */
  z.strictObject({ t: z.literal("lock"), locked: z.boolean() }),
  // WebRTC signaling, relayed only between the host and one guest
  z.strictObject({
    t: z.literal("sdp"),
    to: PeerId,
    kind: z.enum(["offer", "answer"]),
    sdp: z.string().min(1).max(SDP_MAX),
  }),
  /** `cand: null` signals end of candidates. */
  z.strictObject({ t: z.literal("ice"), to: PeerId, cand: IceCandidate.nullable() }),
  /** Guest → host: "send me a fresh offer" (after a reload or a failed connection). */
  z.strictObject({ t: z.literal("want-offer"), to: PeerId }),
]);
export type ClientMsg = z.infer<typeof ClientMsg>;

// ── Room → client ───────────────────────────────────────────────────────────

export const Member = z.strictObject({
  peer: PeerId,
  name: z.string(),
  slot: SlotSchema.nullable(),
  ready: z.boolean(),
  host: z.boolean(),
  /** False while a member's socket is gone but their seat is held for resume. */
  online: z.boolean(),
});
export type Member = z.infer<typeof Member>;

export const RoomState = z.strictObject({
  code: RoomCode,
  players: PlayerCountSchema,
  /** Host is streaming the game. */
  live: z.boolean(),
  /** New members can't join; seats held for reconnects still can. */
  locked: z.boolean(),
  members: z.array(Member),
});
export type RoomState = z.infer<typeof RoomState>;

export const ChatEntry = z.strictObject({
  id: z.int().nonnegative(),
  /** "system" entries are generated by the room (joins, leaves, kicks). */
  kind: z.enum(["user", "system"]),
  peer: PeerId.nullable(),
  name: z.string(),
  text: z.string(),
  ts: z.int(),
});
export type ChatEntry = z.infer<typeof ChatEntry>;

export const ErrorCode = z.enum([
  "bad_message",
  "version_mismatch",
  "rate_limited",
  "room_not_found",
  "room_full",
  "room_locked",
  "name_invalid",
  "name_taken",
  "slot_taken",
  "slot_unavailable",
  "not_host",
  "bad_host_key",
  "peer_not_found",
  "players_below_occupied",
  "not_member",
]);
export type ErrorCode = z.infer<typeof ErrorCode>;

export const ServerMsg = z.discriminatedUnion("t", [
  z.strictObject({
    t: z.literal("welcome"),
    peer: PeerId,
    resume: Secret,
    room: RoomState,
    chat: z.array(ChatEntry),
  }),
  z.strictObject({ t: z.literal("state"), room: RoomState }),
  z.strictObject({ t: z.literal("chat"), entry: ChatEntry }),
  z.strictObject({
    t: z.literal("sdp"),
    from: PeerId,
    kind: z.enum(["offer", "answer"]),
    sdp: z.string(),
  }),
  z.strictObject({ t: z.literal("ice"), from: PeerId, cand: IceCandidate.nullable() }),
  z.strictObject({ t: z.literal("want-offer"), from: PeerId }),
  /** Removed by the host. The socket is closed right after. */
  z.strictObject({ t: z.literal("kicked") }),
  /** `fatal: true` means the socket is closed right after. */
  z.strictObject({ t: z.literal("error"), code: ErrorCode, fatal: z.boolean() }),
]);
export type ServerMsg = z.infer<typeof ServerMsg>;

// ── HTTP ────────────────────────────────────────────────────────────────────

export const CreateRoomReq = z.strictObject({ players: PlayerCountSchema });
export type CreateRoomReq = z.infer<typeof CreateRoomReq>;

export const CreateRoomRes = z.strictObject({ code: RoomCode, hostKey: Secret });
export type CreateRoomRes = z.infer<typeof CreateRoomRes>;

export const RoomInfoRes = z.strictObject({
  code: RoomCode,
  players: PlayerCountSchema,
  openSlots: z.array(SlotSchema),
  hostOnline: z.boolean(),
  live: z.boolean(),
  locked: z.boolean(),
});
export type RoomInfoRes = z.infer<typeof RoomInfoRes>;

/** Proves room membership with the caller's current resume token. */
export const IceReq = z.strictObject({ resume: Secret });
export type IceReq = z.infer<typeof IceReq>;

export const IceServer = z.strictObject({
  urls: z.array(z.string()),
  username: z.string().optional(),
  credential: z.string().optional(),
});
export const IceRes = z.strictObject({
  iceServers: z.array(IceServer),
  /** Which relay is configured: "none" means STUN only (direct connections). */
  relay: z.enum(["cloudflare", "fallback", "none"]),
});
export type IceRes = z.infer<typeof IceRes>;

export const ApiError = z.strictObject({ error: ErrorCode });
export type ApiError = z.infer<typeof ApiError>;
